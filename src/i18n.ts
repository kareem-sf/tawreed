const LOCALE_STORAGE_KEY = 'tawreed-locale';

// Synchronous locale hint so Arabic users get an Arabic first paint, before the async Rust bootstrap lands.
function storedLocale(): string {
  try {
    const saved = localStorage.getItem(LOCALE_STORAGE_KEY);
    return saved === 'ar' || saved === 'en' ? saved : 'en';
  } catch {
    return 'en'; // localStorage unavailable (tests, restricted contexts)
  }
}

i18n.use(initReactI18next).init({
  resources,
  lng: storedLocale(),
  fallbackLng: 'en',
  interpolation: { escapeValue: false },
});

// Shared mirror: covers both the bootstrap-applied settings language and user switches (TitleBar shortcut).
i18n.on('languageChanged', (language) => {
  try {
    localStorage.setItem(LOCALE_STORAGE_KEY, language);
  } catch {
    // localStorage unavailable — hint simply won't persist
  }
});

export default i18n;
